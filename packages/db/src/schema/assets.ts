// Assets schema (T16, spec §6 "assets" block): uploaded files + media.
//
// Table DDL mirrors the spec §6 DDL verbatim (id, workspace_id, key, mime,
// size_bytes, purpose, scan_status, created_at) with two additive columns the
// upload pipeline needs — SPEC-NOTE (T16, flagged to the tech lead):
//   * `confirmed_at` — distinguishes "presigned but never uploaded" from
//     "uploaded, scan pending" so confirm() stays idempotent without
//     overloading scan_status (§6 lifecycle: pending→clean/infected/skipped).
//   * `variants` (jsonb, null until processed) — the §12 `process-image` job
//     stores the WebP/AVIF variant plan (keys, sizes, blur placeholder) here;
//     @formforge/core resolveImageAssetRef maps it onto the T21 ImageAssetRef
//     record {src, srcSet, sizes, blurDataURL, width, height}.
//
// RLS: the tenant_isolation policy is created in drizzle/0007 (this table's
// DDL lands after 0003's future-tables block had already run). The public
// ingest role keeps SELECT/INSERT/UPDATE per TENANCY.md.
//
// Conventions (spec §4): snake_case columns, camelCase TS fields, timestamptz
// in UTC, UUIDv7 ids generated by the app (never by the DB).

import { bigint, index, jsonb, pgTable, text, timestamp, unique, uuid } from "drizzle-orm/pg-core";

export const assets = pgTable(
  "assets",
  {
    id: uuid("id").primaryKey(),
    // denormalized tenant key (spec §6: `workspace_id uuid not null`, no FK)
    workspaceId: uuid("workspace_id").notNull(),
    // object-store key, e.g. `upload/<workspaceId>/<assetId>/<fileName>`
    key: text("key").notNull(),
    // declared mime at presign; overwritten with the SNIFFED type at confirm
    mime: text("mime").notNull(),
    sizeBytes: bigint("size_bytes", { mode: "number" }).notNull(),
    // media | upload (spec §6)
    purpose: text("purpose").notNull(),
    // pending | clean | infected | skipped (spec §6; skipped = no AV in dev)
    scanStatus: text("scan_status").notNull().default("pending"),
    confirmedAt: timestamp("confirmed_at", { withTimezone: true }),
    // process-image output (AssetVariants JSON per @formforge/core/assets)
    variants: jsonb("variants"),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [
    // S3 keys are globally unique — one row per object, ever.
    unique("assets_key_unique").on(table.key),
    // recent-assets listing (media picker) (spec §6 style: tenant + time)
    index("assets_workspace_id_created_at_idx").on(table.workspaceId, table.createdAt.desc()),
  ],
);

export const assetPurposeValues = ["media", "upload"] as const;
export type AssetPurpose = (typeof assetPurposeValues)[number];
export const assetScanStatusValues = ["pending", "clean", "infected", "skipped"] as const;
export type AssetScanStatus = (typeof assetScanStatusValues)[number];

export type AssetTableRow = typeof assets.$inferSelect;
export type NewAssetTableRow = typeof assets.$inferInsert;

export const assetTables = { assets } as const;
